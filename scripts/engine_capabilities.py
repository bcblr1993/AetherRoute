#!/usr/bin/env python3
"""Keeps the app's copy of the engine capability list equal to the engine.

    engine_capabilities.py write [ENGINE]   # regenerate both files
    engine_capabilities.py check [ENGINE]   # fail if either file is stale

ENGINE defaults to build/differential-target/release/clash-rs, which is
built with the app's feature set. `clash-rs --capabilities` prints the
outbound types, rule types, per-protocol networks and Shadowsocks plugins
the engine loads; the app uses them to show unsupported nodes and rules
before connecting.
"""
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
JSON_PATH = ROOT / "Config/EngineCapabilities.json"
SWIFT_PATH = ROOT / "Sources/AetherRouteKit/EngineCapabilities.swift"
DEFAULT_ENGINE = ROOT / "build/differential-target/release/clash-rs"


def swift_set(values):
    return "[" + ", ".join(json.dumps(v) for v in sorted(values)) + "]"


def render_swift(caps):
    networks = ",\n".join(
        f"        {json.dumps(protocol)}: {swift_set(values)}"
        for protocol, values in sorted(caps["networks"].items())
    )
    return f"""// Generated by scripts/engine_capabilities.py from `clash-rs --capabilities`.
// Do not edit: run `python3 scripts/engine_capabilities.py write`.

/// What the shipped engine can load. The profile summary uses it to name
/// nodes and rules the engine would otherwise drop with only a log line.
public enum EngineCapabilities {{
    public static let schema = {caps["schema"]}
    public static let outboundTypes: Set<String> = {swift_set(caps["outboundTypes"])}
    public static let ruleTypes: Set<String> = {swift_set(caps["ruleTypes"])}
    public static let networks: [String: Set<String>] = [
{networks},
    ]
    public static let shadowsocksPlugins: Set<String> = {swift_set(caps["shadowsocksPlugins"])}
}}
"""


def main():
    if len(sys.argv) not in (2, 3) or sys.argv[1] not in ("write", "check"):
        sys.exit(__doc__)
    engine = Path(sys.argv[2]) if len(sys.argv) == 3 else DEFAULT_ENGINE
    output = subprocess.run([str(engine), "--capabilities"], check=True,
                            capture_output=True, text=True).stdout
    caps = json.loads(output)
    expected_json = json.dumps(caps, indent=2) + "\n"
    expected_swift = render_swift(caps)
    if sys.argv[1] == "write":
        JSON_PATH.write_text(expected_json)
        SWIFT_PATH.write_text(expected_swift)
        print(f"wrote {JSON_PATH.relative_to(ROOT)} and {SWIFT_PATH.relative_to(ROOT)}")
        return
    stale = [p.relative_to(ROOT) for p, text in ((JSON_PATH, expected_json), (SWIFT_PATH, expected_swift))
             if not p.exists() or p.read_text() != text]
    if stale:
        sys.exit("engine capabilities are stale: " + ", ".join(map(str, stale))
                 + "\nrun: python3 scripts/engine_capabilities.py write")
    print("Engine capabilities verified: "
          f"outbound={len(caps['outboundTypes'])} rules={len(caps['ruleTypes'])} "
          f"networks={sum(map(len, caps['networks'].values()))} plugins={len(caps['shadowsocksPlugins'])}")


if __name__ == "__main__":
    main()
